/**
 * ADIM 1.4 — Firebase web config → .env.production + .firebaserc
 *
 * Usage:
 *   npm run firebase:init-env
 *   npm run firebase:init-env -- --config firebase/firebase-web-config.json
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')

function parseArgs(argv) {
  const configIdx = argv.indexOf('--config')
  return {
    configPath:
      configIdx >= 0 && argv[configIdx + 1]
        ? path.resolve(root, argv[configIdx + 1])
        : path.join(root, 'firebase', 'firebase-web-config.json'),
  }
}

function readFirebaseWebConfig(filePath) {
  if (!fs.existsSync(filePath)) return null
  const raw = fs.readFileSync(filePath, 'utf8').trim()
  if (!raw) return null

  let parsed
  try {
    parsed = JSON.parse(raw)
  } catch {
    const match = raw.match(/firebaseConfig\s*=\s*(\{[\s\S]*?\});?/m)
    if (!match) throw new Error('JSON parse failed — Firebase Console snippet veya düz JSON kullan')
    parsed = JSON.parse(match[1])
  }

  const config = parsed.firebase ?? parsed
  return {
    apiKey: config.apiKey ?? '',
    authDomain: config.authDomain ?? '',
    projectId: config.projectId ?? '',
    storageBucket: config.storageBucket ?? '',
    messagingSenderId: config.messagingSenderId ?? '',
    appId: config.appId ?? '',
  }
}

function requireField(config, key) {
  const value = String(config[key] ?? '').trim()
  if (!value || value.includes('your-project') || value.includes('REPLACE')) {
    throw new Error(`Eksik veya placeholder: ${key}`)
  }
  return value
}

function writeEnvProduction(config) {
  const lines = [
    '# Generated by npm run firebase:init-env — do not commit (gitignored).',
    '# Vite loads this file automatically for production builds.',
    '',
    `VITE_FIREBASE_API_KEY=${requireField(config, 'apiKey')}`,
    `VITE_FIREBASE_AUTH_DOMAIN=${requireField(config, 'authDomain')}`,
    `VITE_FIREBASE_PROJECT_ID=${requireField(config, 'projectId')}`,
    `VITE_FIREBASE_STORAGE_BUCKET=${requireField(config, 'storageBucket')}`,
    `VITE_FIREBASE_MESSAGING_SENDER_ID=${requireField(config, 'messagingSenderId')}`,
    `VITE_FIREBASE_APP_ID=${requireField(config, 'appId')}`,
    '',
    '# App Check (ADIM 3.3 — P0 zorunlu, rules App Check ister)',
    '# VITE_FIREBASE_APPCHECK_RECAPTCHA_SITE_KEY=',
    '',
    '# Optional monitoring (ADIM 12.3)',
    '# VITE_SENTRY_DSN=',
    '# VITE_RUM_SAMPLE_RATE=0.05',
    '',
  ]
  const body = lines.join('\n')
  fs.writeFileSync(path.join(root, '.env.production'), body, 'utf8')
  fs.writeFileSync(path.join(root, '.env'), body, 'utf8')
}

function writeFirebaserc(projectId) {
  const rc = { projects: { default: projectId } }
  fs.writeFileSync(path.join(root, '.firebaserc'), `${JSON.stringify(rc, null, 2)}\n`, 'utf8')
}

function scaffoldConfigTemplate() {
  const example = path.join(root, 'firebase', 'firebase-web-config.example.json')
  const target = path.join(root, 'firebase', 'firebase-web-config.json')
  if (!fs.existsSync(target) && fs.existsSync(example)) {
    fs.copyFileSync(example, target)
    return target
  }
  return target
}

const { configPath } = parseArgs(process.argv.slice(2))

if (!fs.existsSync(configPath)) {
  const created = scaffoldConfigTemplate()
  console.log('ADIM 1.4 — Firebase web config gerekli.\n')
  console.log('1. Firebase Console → Project settings → Your apps → Web app → Config')
  console.log('2. Değerleri şuraya yapıştır:', path.relative(root, created))
  console.log('3. Tekrar çalıştır: npm run firebase:init-env\n')
  process.exit(1)
}

let config
try {
  config = readFirebaseWebConfig(configPath)
  if (!config) throw new Error('Config dosyası boş')
} catch (error) {
  console.error('Config okunamadı:', error.message)
  console.error('Dosya:', configPath)
  process.exit(1)
}

try {
  const projectId = requireField(config, 'projectId')
  writeEnvProduction(config)
  writeFirebaserc(projectId)
} catch (error) {
  console.error('ADIM 1.4 tamamlanamadı:', error.message)
  console.error('\nfirebase/firebase-web-config.json içindeki placeholder değerleri Console\'dan doldur.')
  process.exit(1)
}

console.log('ADIM 1.4 tamam:')
console.log('  ✓ .env yazıldı (npm run dev)')
console.log('  ✓ .env.production yazıldı')
console.log(`  ✓ .firebaserc → ${config.projectId}`)
console.log('\nFirebase Console → Authentication → Sign-in method → Google → Etkinleştir')
console.log('Authorized domains: localhost')
console.log('\nDoğrula: npm run firebase:verify-setup && npm run env:check:production')
